func TestValidateFragmentRejectsIdentityFields(t *testing.T) {
	for name := range Fragments() {
		t.Run(name, func(t *testing.T) {
			p := Fragments()[name]
			// Mutate a copy to set a forbidden field and verify rejection.
			bad := p
			bad.Image = "evil:latest"
			if err := validateFragment(name, bad); err == nil {
				t.Errorf("expected error for fragment %q with image set", name)
			}
			bad = p
			bad.Extends = "shell"
			if err := validateFragment(name, bad); err == nil {
				t.Errorf("expected error for fragment %q with extends set", name)
			}
		})
	}
}

func TestGenerateYAMLWithCachesAndMounts(t *testing.T) {
	dir := t.TempDir()
	var stdout, stderr bytes.Buffer
	err := Run(context.Background(), Options{
		Profile:    "opencode",
		Fragments:  []string{"npm", "go", "gitconfig", "ssh"},
		ProfileDir: dir,
	}, strings.NewReader(""), &stdout, &stderr)
	if err != nil {
		t.Fatalf("Run: %v\nstderr: %s", err, stderr.String())
	}
	// Note: this test uses mount fragments (gitconfig, ssh) so checkFragmentFiles
	// may emit warnings to stderr if those host files are absent. This test
	// only asserts on the generated file content, not stderr.

	data, err := os.ReadFile(filepath.Join(dir, "opencode.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	output := string(data)

	// Header marker
	if !strings.HasPrefix(output, "# Generated by toolpod init.\n") {
		t.Errorf("missing header marker, got:\n%s", output)
	}

	// extends
	if !strings.Contains(output, "extends: opencode") {
		t.Errorf("missing extends: opencode, got:\n%s", output)
	}

	// No command: [] (omitempty should handle this)
	if strings.Contains(output, "command:") {
		t.Errorf("should not emit command: in override, got:\n%s", output)
	}

	// Caches (alphabetical)
	if !strings.Contains(output, "go: ~/go") {
		t.Errorf("missing go cache, got:\n%s", output)
	}
	if !strings.Contains(output, "npm: ~/.npm") {
		t.Errorf("missing npm cache, got:\n%s", output)
	}

	// Mounts
	if !strings.Contains(output, "~/.gitconfig:") {
		t.Errorf("missing gitconfig mount, got:\n%s", output)
	}
	if !strings.Contains(output, "~/.ssh:") {
		t.Errorf("missing ssh mount, got:\n%s", output)
	}
	if !strings.Contains(output, "~/.ssh/known_hosts:") {
		t.Errorf("missing known_hosts mount, got:\n%s", output)
	}
	if !strings.Contains(output, "read_only: false") {
		t.Errorf("known_hosts should be read_only: false, got:\n%s", output)
	}
}

func TestIntegrationResolveGeneratedProfile(t *testing.T) {
	dir := t.TempDir()
	var stdout, stderr bytes.Buffer
	err := Run(context.Background(), Options{
		Profile:    "opencode",
		Fragments:  []string{"npm", "go", "gitconfig", "ssh"},
		ProfileDir: dir,
	}, strings.NewReader(""), &stdout, &stderr)
	if err != nil {
		t.Fatalf("Run: %v\nstderr: %s", err, stderr.String())
	}

	cat, err := profile.LoadProfiles(dir)
	if err != nil {
		t.Fatalf("LoadProfiles: %v", err)
	}
	cfg, err := profile.ResolveProfile(cat, "opencode")
	if err != nil {
		t.Fatalf("ResolveProfile: %v", err)
	}
	if cfg.Caches["npm"] != "~/.npm" {
		t.Errorf("Caches[npm] = %q, want ~/.npm", cfg.Caches["npm"])
	}
	if cfg.Caches["go"] != "~/go" {
		t.Errorf("Caches[go] = %q, want ~/go", cfg.Caches["go"])
	}
	if cfg.Mounts["~/.gitconfig"].Source != "~/.gitconfig" {
		t.Errorf("gitconfig source = %q", cfg.Mounts["~/.gitconfig"].Source)
	}
	if !cfg.Mounts["~/.gitconfig"].ReadOnly {
		t.Error("gitconfig should be read-only")
	}
	if !cfg.Mounts["~/.ssh"].ReadOnly {
		t.Error("ssh should be read-only")
	}
	if cfg.Mounts["~/.ssh/known_hosts"].ReadOnly {
		t.Error("known_hosts should be read-write")
	}
	if cfg.Image != "ghcr.io/jdx/mise:latest" {
		t.Errorf("Image = %q, want inherited from built-in", cfg.Image)
	}
	if len(cfg.Command) != 1 || cfg.Command[0] != "opencode" {
		t.Errorf("Command = %v, want [opencode] inherited from built-in", cfg.Command)
	}
	// Fragments install mise tools alongside their caches
	if cfg.Tools["node"] != "latest" {
		t.Errorf("Tools[node] = %q, want latest (from npm fragment)", cfg.Tools["node"])
	}
	if cfg.Tools["go"] != "latest" {
		t.Errorf("Tools[go] = %q, want latest (from go fragment)", cfg.Tools["go"])
	}
	if cfg.Tools["opencode"] != "latest" {
		t.Errorf("Tools[opencode] = %q, want latest (inherited from built-in)", cfg.Tools["opencode"])
	}
}

